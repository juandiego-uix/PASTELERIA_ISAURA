create or replace function public.registrar_cambio_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then
    insert into pedido_historial (pedido_id, usuario_id, estado_anterior, estado_nuevo, notas)
    values (new.id, auth.uid(), null, new.estado, new.notas_internas);
  elsif old.estado is distinct from new.estado then
    insert into pedido_historial (pedido_id, usuario_id, estado_anterior, estado_nuevo, notas)
    values (new.id, auth.uid(), old.estado, new.estado, new.notas_internas);
  end if;
  if new.estado = 'Confirmado' and (tg_op = 'INSERT' or old.estado is distinct from new.estado) then new.confirmada_at := now(); end if;
  if new.estado = 'Entregado' and (tg_op = 'INSERT' or old.estado is distinct from new.estado) then new.entregada_at := now(); end if;
  return new;
end;
$$;

