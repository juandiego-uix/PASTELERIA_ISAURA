create table if not exists public.movimientos_inventario (
  id bigint generated by default as identity primary key,
  insumo_id bigint not null references public.insumos(id) on delete cascade,
  pedido_id bigint references public.citas(id) on delete set null,
  tipo text not null check (tipo in ('entrada', 'salida', 'ajuste', 'devolución')),
  cantidad numeric(12, 3) not null check (cantidad > 0),
  motivo text not null default '',
  created_at timestamptz not null default now()
);

create or replace function public.descontar_insumos_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  item jsonb;
  recipe record;
  required_stock numeric;
begin
  for item in select * from jsonb_array_elements(coalesce(new.items, '[]'::jsonb)) loop
    for recipe in select pi.insumo_id, pi.cantidad, i.stock_actual, i.ingrediente
      from producto_insumos pi join insumos i on i.id = pi.insumo_id
      where pi.producto_id = (item->>'id')::bigint loop
      required_stock := recipe.cantidad * greatest(1, (item->>'cantidad')::numeric);
      if recipe.stock_actual < required_stock then
        raise exception 'Stock insuficiente para %', recipe.ingrediente using errcode = 'check_violation';
      end if;
      update insumos set stock_actual = stock_actual - required_stock, updated_at = now() where id = recipe.insumo_id;
      insert into movimientos_inventario (insumo_id, pedido_id, tipo, cantidad, motivo)
      values (recipe.insumo_id, new.id, 'salida', required_stock, 'Pedido nuevo');
    end loop;
  end loop;
  return new;
end;
$$;

create or replace function public.reponer_insumos_pedido()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  item jsonb;
  recipe record;
  restored_stock numeric;
begin
  for item in select * from jsonb_array_elements(coalesce(old.items, '[]'::jsonb)) loop
    for recipe in select pi.insumo_id, pi.cantidad
      from producto_insumos pi
      where pi.producto_id = (item->>'id')::bigint loop
      restored_stock := recipe.cantidad * greatest(1, (item->>'cantidad')::numeric);
      update insumos set stock_actual = stock_actual + restored_stock, updated_at = now() where id = recipe.insumo_id;
      insert into movimientos_inventario (insumo_id, pedido_id, tipo, cantidad, motivo)
      values (recipe.insumo_id, old.id, 'devolución', restored_stock, 'Pedido eliminado');
    end loop;
  end loop;
  return old;
end;
$$;

